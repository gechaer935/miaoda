export type JobCategoryKey = typeof JOB_CATEGORIES[number]['key'];

const LEGACY_CATEGORY_ALIASES: Record<string, JobCategoryKey> = {
  manufacturing: 'machinery',
  legal: 'hr_admin',
  consulting: 'hr_admin',
  trade: 'supply_chain',
  culture_sports: 'media',
};

export function normalizeJobCategory(value: unknown): JobCategoryKey {
  const candidate = String(value || '').trim();
  const directMatch = JOB_CATEGORIES.find((item) => item.key === candidate);
  return directMatch?.key || LEGACY_CATEGORY_ALIASES[candidate] || 'it';
}

export function normalizeJobForCategory(categoryKey: JobCategoryKey, value: unknown): string {
  const category = JOB_CATEGORIES.find((item) => item.key === categoryKey) || JOB_CATEGORIES[0];
  const candidate = String(value || '').trim();
  return (category.jobs as readonly string[]).includes(candidate) ? candidate : category.jobs[0];
}
